import {test,expect} from '@playwright/test';
test.describe.configure({mode:'serial'});
test('graph inspection, simulation, reviewed memory and identity survive a reload',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByText('Stream connected',{exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{level:1})).toHaveText('Secure qualified investor conversations');
  await page.getByRole('button',{name:'Inspect Verify the source documents',exact:true}).click();
  const inspector=page.getByRole('complementary',{name:'Details inspector'});
  await expect(inspector.getByRole('heading',{level:2})).toHaveText('Verify the source documents');
  await page.getByRole('button',{name:'Collapse Make the company ready',exact:true}).click();
  await expect(page.getByRole('button',{name:'Inspect Verify the source documents',exact:true})).toHaveCount(0);
  await page.getByRole('textbox',{name:'Find a directive or task'}).fill('Verify the source');
  await expect(page.getByRole('button',{name:'Inspect Verify the source documents',exact:true})).toBeVisible();
  await page.getByRole('textbox',{name:'Find a directive or task'}).fill('');
  await page.getByRole('button',{name:'Expand Make the company ready',exact:true}).click();
  await page.getByRole('combobox',{name:'Flow direction'}).selectOption('vertical');
  await page.getByRole('button',{name:'Outline',exact:true}).click();
  await expect(page.getByLabel('Directive outline')).toBeVisible();
  await page.getByRole('button',{name:'Map',exact:true}).click();
  await page.getByRole('combobox',{name:'Flow direction'}).selectOption('horizontal');
  const before=await (await page.request.get('/api/workspace')).json();
  await page.getByRole('button',{name:'Step',exact:true}).click();
  await page.getByRole('button',{name:'Open workforce'}).click();
  await inspector.getByRole('button',{name:/Worker 01/}).click();
  await expect(inspector.getByText('working',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Pause worker',exact:true}).click();
  await expect(inspector.getByText('paused',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Resume worker',exact:true}).click();
  await page.getByRole('button',{name:'Next stage',exact:true}).click();
  await expect(inspector.getByText('Checking the simulated result against the task acceptance criteria.',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Next stage',exact:true}).click();
  await page.getByRole('button',{name:'Record a demo review'}).click();
  await page.getByRole('button',{name:'Approve lesson'}).click();
  await expect(inspector.getByText('approved',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('Stream connected',{exact:true})).toBeVisible();
  const after=await (await page.request.get('/api/workspace')).json();
  expect(after.workers.map((w:{id:string})=>w.id)).toEqual(before.workers.map((w:{id:string})=>w.id));
  expect(after.runs).toHaveLength(1);
  await page.getByRole('button',{name:'Open workforce'}).click();
  await inspector.getByRole('button',{name:/Worker 01/}).click();
  await expect(inspector.getByText('approved',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Name catalog',exact:true}).click();
  await expect(inspector.getByText(/Availability is unverified/)).toBeVisible();
  await expect(inspector.getByText('Browse 601 names')).toBeVisible();
  expect(errors).toEqual([]);
});
test('small screens keep keyboard-accessible inspection and no horizontal overflow',async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto('/');
  await expect(page.getByText('Stream connected',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Outline',exact:true}).click();
  const item=page.getByLabel('Directive outline').getByRole('button',{name:/task Verify the source documents/});
  await item.focus();await page.keyboard.press('Enter');
  await expect(page.getByRole('complementary').getByRole('heading',{level:2})).toHaveText('Verify the source documents');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
