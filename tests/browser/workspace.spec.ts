test('workers move to observed assignments and preserve identity inside collapsed branches',async({page})=>{
  await page.goto('/');await expect(page.getByText('Stream connected',{exact:true})).toBeVisible();
  const snapshot=await (await page.request.get('/api/workspace')).json();const id=snapshot.workers.find((w:{label:string})=>w.label==='Worker 01').id;
  const worker=page.locator(`[data-worker-id="${id}"]`);
  await expect(worker).toHaveAttribute('data-task','idle');
  const before=await worker.locator('..').evaluate(e=>getComputedStyle(e).transform);
  await page.getByRole('button',{name:'Step',exact:true}).click();
  await expect(worker).toHaveAttribute('data-task','Prepare the company brief');
  await expect.poll(()=>worker.locator('..').evaluate(e=>getComputedStyle(e).transform)).not.toBe(before);
  await page.getByRole('button',{name:'Fit view',exact:true}).click();
  await worker.getByRole('button',{name:'Inspect Worker 01',exact:true}).focus();
  await worker.getByRole('button',{name:'Inspect Worker 01',exact:true}).hover();
  await expect(worker.getByRole('tooltip')).toBeVisible();
  await expect(worker.getByRole('tooltip')).toContainText('Simulation');
  await page.getByRole('button',{name:'Collapse Make the company ready',exact:true}).click();
  await expect(worker).toHaveAttribute('data-task','Prepare the company brief');
  await expect(worker.getByText('↳ Inside branch')).toBeVisible();
  await worker.getByRole('button',{name:'Inspect Worker 01',exact:true}).click();
  await expect(page.getByRole('complementary').getByRole('heading',{level:2})).toHaveText('Worker 01');
  await page.getByRole('combobox',{name:'Animation preference'}).selectOption('reduced');
  await expect(page.locator('.worker-position.travel-enabled')).toHaveCount(0);
  await page.getByRole('combobox',{name:'Flow direction'}).selectOption('vertical');
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('prime-directive:local-demo:view:v1')!).orientation)).toBe('vertical');
  await page.reload();
  await expect(page.getByRole('combobox',{name:'Flow direction'})).toHaveValue('vertical');
  await expect(page.getByRole('combobox',{name:'Animation preference'})).toHaveValue('reduced');
  await expect(page.getByRole('complementary').getByRole('heading',{level:2})).toHaveText('Worker 01');
  await page.getByRole('textbox',{name:'Find a directive or task'}).fill('Prepare the company brief');
  await expect(page.getByRole('button',{name:'Inspect Prepare the company brief',exact:true})).toBeVisible();
});
test('malformed saved state falls back safely and system reduced motion is honored',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.addInitScript(()=>localStorage.setItem('prime-directive:local-demo:view:v1','{"version":1,"collapsed":"hide-everything","execute":"send"}'));
  await page.goto('/');await expect(page.getByText('Stream connected',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Inspect Secure qualified investor conversations',exact:true})).toBeVisible();
  await expect(page.getByRole('combobox',{name:'Flow direction'})).toHaveValue('horizontal');
  await expect(page.locator('.worker-position.travel-enabled')).toHaveCount(0);
});
test('a disconnected activity stream freezes travel and labels the last observed state',async({page})=>{
  await page.route('**/api/events?*',route=>route.abort('failed'));
  await page.goto('/');
  await expect(page.getByText('Stream disconnected',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'▶ Run demo',exact:true})).toBeDisabled();
  await expect(page.locator('.worker-position.travel-enabled')).toHaveCount(0);
  await expect(page.getByText('last observed',{exact:true}).first()).toBeVisible();
  await page.unroute('**/api/events?*');await page.reload();
  await expect(page.getByText('Stream connected',{exact:true})).toBeVisible();
});
